from html import escape


def render_html(profile):
    def esc(value):
        return escape(str(value), quote=True)

    def bullets(items):
        return "<ul>" + "".join(f"<li>{esc(item)}</li>" for item in items) + "</ul>"

    ai = profile["ai"]
    if ai["status"] == "generated":
        explanation = (
            f"<p>{esc(ai['summary'])}</p>"
            f"<p><strong>Possible row meaning</strong> {esc(ai['possible_row_meaning'])}</p>"
            "<h3>Suggested next steps</h3>" + bullets(ai["next_steps"]) +
            "<h3>Caveats</h3>" + bullets(ai["caveats"]) +
            f"<p class='muted'>Generated by {esc(ai['model'])}. Interpretations require review.</p>"
        )
    elif ai["status"] == "failed":
        explanation = "<p>AI explanation was unavailable. The computed profile is complete.</p>"
    else:
        explanation = "<p>Run with --ai-model to add an AI explanation using an Ollama model.</p>"

    bars, table_rows = [], []
    for column in profile["columns"]:
        pct = column["missing_pct"]
        bars.append(
            f"<div class='bar-row'><span>{esc(column['name'])}</span>"
            f"<meter min='0' max='100' value='{pct}' aria-label='{esc(column['name'])} missing percentage'></meter>"
            f"<strong>{pct:.1f}%</strong></div>"
        )
        stats = column.get("stats", {})
        numeric = " / ".join("—" if stats.get(k) is None else f"{stats[k]:.4g}"
                             for k in ("min", "median", "max")) if stats else "—"
        note = []
        if column.get("possible_identifier"):
            note.append("All observed values unique")
        if column.get("infinite"):
            note.append(f"{column['infinite']} infinite")
        if column.get("iqr_outliers"):
            note.append(f"{column['iqr_outliers']} outside 1.5×IQR")
        cells = [column["name"], column["kind"], column["non_missing"], column["unique"],
                 f"{column['missing']} ({pct:.1f}%)", numeric, "; ".join(note) or "—"]
        table_rows.append("<tr>" + "".join(f"<td>{esc(c)}</td>" for c in cells) + "</tr>")
    patterns = [
        f"{', '.join(p['columns'])} missing together in {p['rows']} rows."
        for p in profile["missing_patterns"]
    ]
    cards = [
        ("Rows scanned", f"{profile['rows']:,}"),
        ("Columns", profile["columns_count"]),
        ("Missing cells", f"{profile['missing_pct']:.1f}%"),
        ("Incomplete rows", f"{profile['incomplete_rows']:,}"),
        ("Duplicate rows", f"{profile['duplicate_rows']:,}"),
    ]
    card_html = "".join(f"<div class='card'><span>{label}</span><strong>{value}</strong></div>"
                        for label, value in cards)
    return """<!doctype html><html lang="en"><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>DatasetBrief — """ + esc(profile["dataset"]) + """</title>
<style>
*{box-sizing:border-box}body{font:16px/1.6 Inter,system-ui,sans-serif;margin:0;background:#f3f5f3;color:#20372d}
main{max-width:1120px;margin:auto;padding:48px 24px}h1{font-size:clamp(28px,4vw,46px);line-height:1.2;overflow-wrap:anywhere}
h2{font-size:21px}h3{font-size:16px}p{max-width:85ch}.brand{font-size:14px;letter-spacing:.08em;font-weight:700}
.muted,.card span{color:#586c62}.cards{display:flex;gap:12px;flex-wrap:wrap}
.card,section{background:white;border:1px solid #d9e2dc;border-radius:12px;padding:22px}
.card{flex:1;min-width:145px}.card strong{display:block;font-size:28px}section{margin-top:20px}
.bar-row{display:grid;grid-template-columns:minmax(80px,1fr) 2fr 65px;gap:16px;align-items:center;margin:12px 0}
.bar-row span{overflow-wrap:anywhere}meter{width:100%;height:20px;accent-color:#278261}
.scroll{overflow:auto}table{border-collapse:collapse;width:100%;font-size:14px}
th,td{text-align:left;padding:12px;border-bottom:1px solid #e5ebe6;vertical-align:top}td{max-width:320px;overflow-wrap:anywhere}
th{white-space:nowrap}li{margin-bottom:8px}footer{margin-top:24px;font-size:13px;color:#586c62}
@media print{body{background:white}main{padding:0}section,.card{break-inside:avoid}}
</style><main><div class="brand">DatasetBrief</div><h1>""" + esc(profile["dataset"]) + """</h1>
<p class="muted">""" + esc(profile["scan_note"]) + """ Statistics describe the loaded rows.</p>
<div class="cards">""" + card_html + """</div>
<section><h2>AI interpretation</h2>""" + explanation + """</section>
<section><h2>Missing values by column</h2>""" + "".join(bars) + """
<p class="muted">""" + esc(profile["missing_policy"]) + """</p></section>
<section><h2>Quality findings</h2>""" + bullets(profile["findings"] or ["No missing, constant-column or duplicate-row issues detected."]) + """
</section><section><h2>Missingness patterns</h2>""" + bullets(patterns or ["No missing values detected."]) + """
<p class="muted">Up to ten most frequent patterns. Each row contributes to one pattern. These patterns do not establish why data is missing.</p>
</section><section><h2>Column profile</h2><div class="scroll"><table>
<thead><tr><th>Column</th><th>Type</th><th>Present</th><th>Unique</th><th>Missing</th>
<th>Min / Median / Max</th><th>Notes</th></tr></thead><tbody>""" + "".join(table_rows) + """
</tbody></table></div><p class="muted">Numeric summaries exclude infinite values. IQR flags are descriptive, not proof of invalid data.
Text columns may contain dates or categories. Unique values alone do not establish an identifier.</p></section>
<footer>Generated locally with DatasetBrief. Counts are computed by pandas. AI receives column names and aggregate statistics when enabled.</footer>
</main></html>"""
